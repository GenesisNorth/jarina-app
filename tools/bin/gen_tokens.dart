// Generates packages/jarina_ui/lib/src/tokens/jarina_tokens.g.dart from the
// prototype's design/tokens.json.
//
// Usage: dart run tools/bin/gen_tokens.dart [tokens.json] [out.dart]
import 'dart:convert';
import 'dart:io';

import 'package:path/path.dart' as p;

void main(List<String> args) {
  final root = p.normalize(p.join(p.dirname(Platform.script.toFilePath()), '../..'));
  final input = args.isNotEmpty ? args[0] : p.join(root, '../jarina-mobile/design/tokens.json');
  final output = args.length > 1 ? args[1] : p.join(root, 'packages/jarina_ui/lib/src/tokens/jarina_tokens.g.dart');

  final json = jsonDecode(File(input).readAsStringSync()) as Map<String, dynamic>;
  final color = json['color'] as Map<String, dynamic>;
  final b = StringBuffer()
    ..writeln('// GENERATED by tools/bin/gen_tokens.dart from design/tokens.json. Do not edit.')
    ..writeln('// ignore_for_file: public_member_api_docs')
    ..writeln()
    ..writeln("import 'dart:ui';")
    ..writeln();

  void colorClass(String name, Map<String, dynamic> group) {
    b.writeln('abstract final class $name {');
    for (final e in group.entries) {
      final hex = ((e.value as Map)['value'] as String).replaceFirst('#', '');
      b.writeln('  static const ${_camel(e.key)} = Color(0xFF${hex.toUpperCase()});');
    }
    b.writeln('}\n');
  }

  colorClass('BrandColors', color['brand'] as Map<String, dynamic>);
  colorClass('LightColors', color['light'] as Map<String, dynamic>);
  colorClass('DarkColors', color['dark'] as Map<String, dynamic>);

  final font = json['font'] as Map<String, dynamic>;
  final family = (font['family'] as Map<String, dynamic>)['value'];
  b
    ..writeln('abstract final class TypeTokens {')
    ..writeln("  static const family = '$family';");
  final styles = font['styles'] as Map<String, dynamic>;
  for (final e in styles.entries) {
    final s = e.value as Map<String, dynamic>;
    final n = _camel(e.key);
    b
      ..writeln('  static const double ${n}Size = ${s['size']};')
      ..writeln('  static const ${n}Weight = FontWeight.w${s['weight']};')
      ..writeln('  static const double ${n}LetterSpacing = ${s['letterSpacing'] ?? 0};');
  }
  b.writeln('}\n');

  void numClass(String name, Map<String, dynamic> group) {
    b.writeln('abstract final class $name {');
    for (final e in group.entries) {
      b.writeln('  static const double ${_camel(e.key)} = ${(e.value as Map)['value']};');
    }
    b.writeln('}\n');
  }

  numClass('RadiusTokens', json['radius'] as Map<String, dynamic>);
  numClass('SpacingTokens', json['spacing'] as Map<String, dynamic>);

  final frame = (json['frame'] as Map<String, dynamic>)['mobile'] as Map<String, dynamic>;
  b
    ..writeln('abstract final class FrameTokens {')
    ..writeln('  /// Reference artboard the designs were drawn at.')
    ..writeln("  static const designSize = Size(${frame['width']}, ${frame['height']});")
    ..writeln('}');

  File(output)
    ..createSync(recursive: true)
    ..writeAsStringSync(b.toString());
  stdout.writeln('Tokens → ${p.relative(output)}');
}

String _camel(String s) {
  final parts = s.split(RegExp('[-_ ]'));
  return parts.first + parts.skip(1).map((w) => w[0].toUpperCase() + w.substring(1)).join();
}
